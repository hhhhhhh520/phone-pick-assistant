def seed_database():
    """初始化数据库并填充种子数据"""
    print("正在初始化数据库...")
    init_db()

    db = SessionLocal()
    try:
        # 检查是否已有数据
        existing_count = db.query(Phone).count()
        if existing_count > 0:
            print(f"数据库已有 {existing_count} 条记录，跳过种子数据")
            return

        print("正在插入种子数据...")
        for phone_data in PHONES_DATA:
            phone = Phone(
                brand=phone_data["brand"],
                model=phone_data["model"],
                price=phone_data["price"],
                release_date=phone_data.get("release_date"),
                screen_size=phone_data.get("screen_size"),
                screen_type=phone_data.get("screen_type"),
                screen_refresh=phone_data.get("screen_refresh"),
                processor=phone_data.get("processor"),
                ram=phone_data.get("ram"),
                storage=phone_data.get("storage"),
                camera_main=phone_data.get("camera_main"),
                camera_ultra=phone_data.get("camera_ultra"),
                camera_telephoto=phone_data.get("camera_telephoto"),
                camera_front=phone_data.get("camera_front"),
                battery=phone_data.get("battery"),
                charging_wired=phone_data.get("charging_wired"),
                charging_wireless=phone_data.get("charging_wireless"),
                weight=phone_data.get("weight"),
                features=json.dumps(phone_data.get("features", []), ensure_ascii=False),
                url=phone_data.get("url"),
                pros=json.dumps(phone_data.get("pros", []), ensure_ascii=False),
                cons=json.dumps(phone_data.get("cons", []), ensure_ascii=False),
                suitable_for=json.dumps(phone_data.get("suitable_for", []), ensure_ascii=False),
            )
            db.add(phone)

        db.commit()
        print(f"成功插入 {len(PHONES_DATA)} 条手机数据")

        # 验证数据
        all_phones = db.query(Phone).all()
        print(f"\n数据库中共有 {len(all_phones)} 款手机:")
        brands = {}
        for phone in all_phones:
            brands[phone.brand] = brands.get(phone.brand, 0) + 1
        for brand, count in brands.items():
            print(f"  - {brand}: {count} 款")

    except Exception as e:
        print(f"错误: {e}")
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_database()
