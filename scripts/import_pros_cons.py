def match_phone(db, keyword):
    """改进的匹配逻辑：品牌感知匹配"""
    phones = db.query(Phone).all()

    # 1. 精确匹配 model 或 brand+model
    for p in phones:
        if p.model == keyword or f"{p.brand} {p.model}" == keyword:
            return p

    # 2. 提取品牌和核心词
    brand_aliases = {
        '小米': ['小米', 'Xiaomi', 'REDMI', 'Redmi', '红米'],
        'OPPO': ['OPPO'],
        'vivo': ['vivo'],
        '荣耀': ['荣耀'],
        '一加': ['一加', 'OnePlus'],
        '真我': ['真我', 'realme', 'Realme'],
        'iQOO': ['iQOO'],
        '红魔': ['红魔', '努比亚'],
        '努比亚': ['努比亚', '红魔'],
        'ROG': ['ROG'],
        '魅族': ['魅族', 'Meizu'],
        '蔚来': ['蔚来', 'NIO'],
    }

    keyword_brand = None
    core = keyword
    for brand_key, aliases in brand_aliases.items():
        for alias in aliases:
            if keyword.startswith(alias):
                keyword_brand = brand_key
                core = keyword[len(alias):].strip()
                break
        if keyword_brand:
            break

    if not core:
        return None

    # 3. 品牌感知的包含匹配
    candidates = []
    for p in phones:
        model_match = core in p.model
        if not model_match:
            continue

        # 如果 keyword 有品牌，phone 的品牌必须匹配
        if keyword_brand:
            phone_brand_match = False
            if keyword_brand in brand_aliases:
                for alias in brand_aliases[keyword_brand]:
                    if alias in p.brand or alias in p.model:
                        phone_brand_match = True
                        break
            if not phone_brand_match:
                continue

        candidates.append(p)

    if len(candidates) == 1:
        return candidates[0]

    if candidates:
        # 优先选 model 完全包含 core 的（而非只是部分匹配）
        # 然后选最短的（最精确）
        candidates.sort(key=lambda p: len(p.model))
        return candidates[0]

    return None


def main():
    db = SessionLocal()

    matched = 0
    unmatched = 0
    unmatched_names = []

    for keyword, pros, cons in PHONE_DATA:
        phone = match_phone(db, keyword)

        if not phone:
            unmatched += 1
            unmatched_names.append(keyword)
            print(f'  MISS:  {keyword}')
            continue

        # 验证匹配
        full = f"{phone.brand} {phone.model}"

        # 直接通过（match_phone 已做了品牌验证）
        phone.pros = json.dumps(pros, ensure_ascii=False)
        phone.cons = json.dumps(cons, ensure_ascii=False)
        matched += 1
        print(f'  OK:    {keyword} -> {full}')

    db.commit()
    db.close()

    print(f'\n=== 结果 ===')
    print(f'匹配成功: {matched}')
    print(f'未找到: {unmatched}')

    if unmatched_names:
        print(f'\n未找到的手机:')
        for n in unmatched_names:
            print(f'  - {n}')


if __name__ == '__main__':
    main()
